"""Read-only diagnostics of the frozen comparison; no model or threshold search."""
import argparse
import ast
from collections import Counter
import json
from pathlib import Path

import pandas as pd
from v09_supervised_filter import FrozenLogit


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--run', type=Path, required=True)
    run = parser.parse_args().run.resolve()
    summary = json.loads((run / 'summary.json').read_text(encoding='utf-8'))
    labels = json.loads((run / 'training-labels.json').read_text(encoding='utf-8'))
    model = FrozenLogit(json.loads((run / 'models/logit.json').read_text(encoding='utf-8')))
    eligible = [r for r in labels if r['status'] == 'eligible']
    confusion = Counter((r['y'], int(model.score(r['state']) >= .5)) for r in eligible)
    records = []
    for result in summary['results']:
        if result['policy'] != 'supervised':
            continue
        folder = run / f"{result['period']}_{result['case']}"
        decisions = pd.read_csv(folder / 'gate-decisions.csv', float_precision='round_trip')
        opportunities = decisions[decisions.pending_before > 0]
        states = [ast.literal_eval(s) for s in opportunities.state]
        assert all(abs(model.score(s) - p) < 1e-12 for s, p in zip(states, opportunities.score))
        records.append({
            'period': result['period'], 'stress': result['stress'],
            'opportunity_batches': len(opportunities),
            'min_score': float(opportunities.score.min()),
            'max_score': float(opportunities.score.max()),
            'accepted': int((opportunities.action == 0).sum()),
            'unique_states': sorted({tuple(s) for s in states}),
            'all_opportunities_empty_account': bool((opportunities.positions_before == 0).all()),
            'closed_trades': result['closed_trades'], 'total_return': result['total_return'],
        })
    result = {
        'kind': 'Frozen model diagnostics; no retuning',
        'training_only_confusion': [
            {'actual': actual, 'predicted': predicted, 'count': confusion[(actual, predicted)]}
            for actual in [0, 1] for predicted in [0, 1]
        ],
        'training_score_min': min(model.score(r['state']) for r in eligible),
        'training_score_max': max(model.score(r['state']) for r in eligible),
        'training_in_sample_is_not_validation': True,
        'evaluation': records,
        'interpretation': 'Every observed empty-account opportunity scores below the frozen threshold. '
                          'Rejecting all entries keeps portfolio exposure, drawdown and age at their empty-account values. '
                          'This is observed policy degeneracy, not a successful low-risk trading strategy. '
                          'Training outcomes were generated by the baseline portfolio, not the deployed gate portfolio.',
        'uncalibrated_scores_not_estimated_trade_win_rates': True,
    }
    with (run / 'supervised-diagnostics.json').open('x', encoding='utf-8') as stream:
        json.dump(result, stream, ensure_ascii=False, indent=2, allow_nan=False)
    print(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__':
    main()
